"""Generate the Android launch wordmark as VectorDrawables.

    pip install fonttools brotli uharfbuzz
    python scripts/android-splash-wordmark.py

Traces "spritz" from app/fonts/playfair-display-latin-wght-normal.woff2
(72dp, weight 400, kerned with HarfBuzz like the browser) and centers it
the way the web launch layer centers .launch-screen__word: a 72dp line box
(line-height 1) centered in the canvas, baseline from the OS/2 typo metrics.
Checked against a Chromium render of the same CSS: same bounding box to
within 1px at 4x.

Writes:
  android/app/src/main/res/drawable/launch_wordmark_icon.xml  288dp canvas,
      windowSplashScreenAnimatedIcon (Android 12+ masks to a 192dp circle;
      the word's widest point is 94.7dp from center, so keep the size).
  android/app/src/main/res/drawable/launch_wordmark.xml       200x100dp,
      used by drawable/launch_splash.xml.

Re-run if the wordmark font, size or colour changes in app/globals.css,
and regenerate the iOS SplashWordmark images to match.
"""
import io
import re
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "app/fonts/playfair-display-latin-wght-normal.woff2"
OUT = ROOT / "android/app/src/main/res/drawable"
TEXT, SIZE, COLOR = "spritz", 72.0, "#1F3F2E"

font = TTFont(FONT)
font.flavor = None
buf = io.BytesIO()
font.save(buf)
hbfont = hb.Font(hb.Face(buf.getvalue()))
shaped = hb.Buffer()
shaped.add_str(TEXT)
shaped.guess_segment_properties()
hb.shape(hbfont, shaped, {"kern": True, "liga": True})

scale = SIZE / font["head"].unitsPerEm
os2 = font["OS/2"]
asc, desc = os2.sTypoAscender * scale, -os2.sTypoDescender * scale
glyphs = font.getGlyphSet()
order = font.getGlyphOrder()
advance = sum(p.x_advance for p in shaped.glyph_positions) * scale


def path_for(width, height):
    top = (height - SIZE) / 2
    baseline = top + (SIZE - (asc + desc)) / 2 + asc
    x = (width - advance) / 2
    parts = []
    for info, pos in zip(shaped.glyph_infos, shaped.glyph_positions):
        pen = SVGPathPen(glyphs)
        glyphs[order[info.codepoint]].draw(
            TransformPen(pen, (scale, 0, 0, -scale, x + pos.x_offset * scale, baseline - pos.y_offset * scale))
        )
        parts.append(pen.getCommands())
        x += pos.x_advance * scale
    d = " ".join(parts)
    return re.sub(r"-?\d+\.\d+", lambda m: ("%.2f" % float(m.group())).rstrip("0").rstrip("."), d)


HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/android-splash-wordmark.py from
     app/fonts/playfair-display-latin-wght-normal.woff2: "spritz", 72dp
     Playfair 400 (kerned), #1F3F2E, centered the way the web launch layer
     centers .launch-screen__word. Vector so it stays sharp at every
     density. Do not hand-edit; re-run the script. -->
"""


def vector(width, height, note=""):
    return f"""{HEADER}{note}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width}dp"
    android:height="{height}dp"
    android:viewportWidth="{width}"
    android:viewportHeight="{height}">
    <path
        android:fillColor="{COLOR}"
        android:pathData="{path_for(width, height)}" />
</vector>
"""


ICON_NOTE = """<!-- Android 12+ splash icon: 288dp canvas. The system masks it to a 192dp
     circle; the widest point of the word is 94.7dp from center, inside it. -->
"""
(OUT / "launch_wordmark_icon.xml").write_text(vector(288, 288, ICON_NOTE), encoding="utf-8")
(OUT / "launch_wordmark.xml").write_text(vector(200, 100), encoding="utf-8")
print("Wrote launch_wordmark_icon.xml and launch_wordmark.xml")
